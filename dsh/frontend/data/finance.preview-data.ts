function amount(minorUnits: number): string {
  try {
    return new Intl.NumberFormat('ar-YE', { style: 'decimal', maximumFractionDigits: 0 }).format(minorUnits) + ' ر.ي';
  } catch {
    return minorUnits.toLocaleString() + ' ر.ي';
  }
}

